"""Read-only source catalog. Original files are retained; this is not old Git history."""
from datetime import datetime,timezone
import hashlib
import json
from pathlib import Path
import shutil

ROOT=Path(__file__).resolve().parents[1]
OLD=Path('D:/传智杯')


def sha(p):
    h=hashlib.sha256()
    with p.open('rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
    return h.hexdigest().upper()


def main():
    entries=[]
    for phase in ('m1-cli','m1-page','m2-local','m2-lan','m3','m4'):
        for p in sorted((OLD/'records'/phase).rglob('*')):
            if p.is_file():
                entries.append(dict(phase=phase,source=str(p),size=p.stat().st_size,sha256=sha(p),
                                    filesystem_modified_utc=datetime.fromtimestamp(p.stat().st_mtime,timezone.utc).isoformat(),
                                    note='Filesystem time is metadata, not proof of original creation time'))
    path=ROOT/'docs/legacy/phases-catalog.json'
    path.write_text(json.dumps(dict(cataloged_at=datetime.now(timezone.utc).isoformat(),
          scope='All files currently under the six named prototype records directories; originals kept in place, not copied or converted to historical Git',
          entries=entries),ensure_ascii=False,indent=2),encoding='utf-8')
    source=OLD/'versions/goal-onboarding-20261101/docs/development-history/exports-20261101'
    target=ROOT/'docs/legacy/prompt-exports-20261101';target.mkdir(exist_ok=False)
    for p in source.iterdir():
        if p.is_file():shutil.copyfile(p,target/p.name)
    vendor=OLD/'artifacts/portable-runtime/python-3.13.17-embed-amd64.zip'
    reuse=json.loads((ROOT/'docs/reuse.json').read_text(encoding='utf-8'))
    reuse['vendor_runtime']=dict(origin=str(vendor),sha256=sha(vendor),official_url='https://www.python.org/ftp/python/3.13.17/python-3.13.17-embed-amd64.zip',
         use='Existing official embedded runtime; no download in this run. App/tool-runtime marker and module-path configuration generated by this rebuild.')
    reuse['model_weights']=dict(origin=str(OLD/'artifacts/local-model/Qwen2.5-0.5B-Instruct'),
         upstream='https://huggingface.co/Qwen/Qwen2.5-0.5B-Instruct',revision='7ae557604adf67be50417f59c2c2f167def9a775',
         weights_sha256='FDF756FA7FCBE7404D5C60E26BFF1A0C8B8AA1F72CED49E7DD0210FE288FB7FE',
         use='Existing local model, no model download. Original model environment and weights retained; inference program written this run.')
    (ROOT/'docs/reuse.json').write_text(json.dumps(reuse,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(dict(cataloged_files=len(entries),bytes=sum(e['size'] for e in entries),historical_exports_copied=True,originals_modified=False)))


if __name__=='__main__':main()
